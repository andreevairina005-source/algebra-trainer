// Перемешивает варианты ответов так, чтобы правильный не всегда был первым
const shuffleQuiz = (quiz) =>
  quiz.map((item) => {
    const order = item.options.map((_, i) => i);
    for (let i = order.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [order[i], order[j]] = [order[j], order[i]];
    }
    return {
      question: item.question,
      options: order.map((i) => item.options[i]),
      correct: order.indexOf(item.correct)
    };
  });

const loadSavedModule = () => {
  try {
    const savedId = localStorage.getItem('algebra_active_topic');
    if (savedId) {
      const index = modules.findIndex((m) => m.id === parseInt(savedId, 10));
      if (index !== -1) return index;
    }
  } catch (e) {
    // хранилище недоступно — просто начинаем с первой темы
  }
  return 0;
};

const getGrade = (score, total) => {
  const percent = (score / total) * 100;
  if (percent >= 90) return 5;
  if (percent >= 70) return 4;
  if (percent >= 50) return 3;
  return 2;
};

